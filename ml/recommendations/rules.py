# Rule 2: Backlog Recovery Recommendation
# ---------------------------------------------------------------------------

class BacklogRecommendationRule(BaseRecommendationRule):
    """
    Evaluates backlog count against institutional risk policy,
    SHAP contributions, and backlog clearance simulations.
    """
    def evaluate(
        self,
        raw_data: Dict[str, Any],
        cgpa_prediction: Optional[Any],
        risk_prediction: Optional[Any],
        explanation: Optional[Any],
        simulation_data: Optional[Dict[str, Any]],
    ) -> Optional[CandidateRecommendation]:
        backlogs = raw_data.get("backlogs")
        if backlogs is None:
            return None

        bl_count = int(backlogs)
        if bl_count <= 0:
            return None

        shap_val = self._extract_shap_for_feature(explanation, "backlogs")
        sim_delta = simulation_data.get("backlogs") if simulation_data else None

        if bl_count >= RecommendationPolicyConfig.BACKLOG_CRITICAL_THRESHOLD:
            priority = RecommendationPriority.CRITICAL
            action = (
                f"You have {bl_count} active course backlogs, which severely impacts academic trajectory and "
                f"graduation progress. Formulate a structured backlog clearance plan with your academic advisor, "
                f"registering for the earliest available supplementary or remedial examinations."
            )
            time_horizon = TimeHorizon.THIS_WEEK
            ranking_score = 50.0 + bl_count * 5.0
        elif bl_count >= RecommendationPolicyConfig.BACKLOG_WARNING_THRESHOLD:
            priority = RecommendationPriority.CRITICAL
            action = (
                f"You have {bl_count} active backlog(s). Focus targeted preparation on outstanding subjects "
                f"and register for upcoming remedial or clearance exam windows to restore good standing."
            )
            time_horizon = TimeHorizon.THIS_WEEK
            ranking_score = 45.0 + bl_count * 5.0
        else:
            priority = RecommendationPriority.HIGH
            action = (
                f"Clear active backlogs ({bl_count}) at the earliest opportunity to prevent cumulative prerequisite bottlenecks."
            )
            time_horizon = TimeHorizon.NEXT_30_DAYS
            ranking_score = 35.0

        if shap_val is not None and shap_val < -0.2:
            ranking_score += abs(shap_val) * 10.0

        impact = self._determine_simulation_impact(sim_delta)
        if impact == ExpectedImpact.UNKNOWN:
            impact = ExpectedImpact.HIGH

        sources = [RecommendationSource.ACADEMIC_DATA, RecommendationSource.RISK_POLICY]
        if shap_val is not None:
            sources.append(RecommendationSource.XAI)
        if sim_delta:
            sources.append(RecommendationSource.WHAT_IF_SIMULATION)
        source = RecommendationSource.COMBINED if len(sources) > 1 else sources[0]

        impact_detail = None
        sim_val = None
        if sim_delta:
            sim_val = sim_delta.get("simulated_value")
            cgpa_diff = sim_delta.get("cgpa_delta", 0.0)
            trans = sim_delta.get("risk_transition", "")
            impact_detail = f"Simulating backlog clearance (to {sim_val}) yields +{cgpa_diff:.2f} predicted CGPA ({trans})."

        evidence = [
            CandidateEvidence(
                factor="backlogs",
                display_name="Active Backlogs",
                current_value=bl_count,
                target_or_threshold=0,
                unit="courses",
                source=source,
                simulated_value=sim_val,
                shap_contribution=shap_val,
                impact_detail=impact_detail,
            )
        ]

        return CandidateRecommendation(
            id="rec-backlog-clearance",
            title="Prioritize Backlog Recovery Plan",
            priority=priority,
            category=RecommendationCategory.BACKLOG_RECOVERY,
            evidence=evidence,
            action=action,
            expected_impact=impact,
            source=source,
            time_horizon=time_horizon,
            risk_factor="Backlogs",
            technical_details={
                "backlog_count": bl_count,
                "shap_contribution": shap_val,
                "simulation_applied": bool(sim_delta),
            },
            ranking_score=ranking_score,
        )



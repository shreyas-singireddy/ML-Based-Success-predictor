# Rule 6: Strength Maintenance & Advanced Growth Rule
# ---------------------------------------------------------------------------

class StrengthMaintenanceRule(BaseRecommendationRule):
    """
    For high-performing or improving students with zero backlogs and good attendance.
    Ensures balanced recommendations without inventing false critical issues.
    """
    def evaluate(
        self,
        raw_data: Dict[str, Any],
        cgpa_prediction: Optional[Any],
        risk_prediction: Optional[Any],
        explanation: Optional[Any],
        simulation_data: Optional[Dict[str, Any]],
    ) -> Optional[CandidateRecommendation]:
        att = float(raw_data.get("attendance_percentage") or 0.0)
        bl = int(raw_data.get("backlogs") or 0)
        cgpa = float(raw_data.get("previous_cgpa") or 0.0)
        risk_lvl = getattr(risk_prediction, "risk_level", "LOW") if risk_prediction else "LOW"

        # Only applies to strong standing students (LOW or moderate risk with strong indicators)
        if bl == 0 and att >= RecommendationPolicyConfig.ATTENDANCE_SAFE_TARGET and cgpa >= RecommendationPolicyConfig.CGPA_WARNING_THRESHOLD:
            priority = RecommendationPriority.LOW
            action = (
                f"You are maintaining strong academic fundamentals (Attendance: {att:.1f}%, Zero backlogs, "
                f"CGPA: {cgpa:.2f}). Continue your current study routines, explore academic projects or honors coursework, "
                f"and consider peer mentoring opportunities."
            )
            time_horizon = TimeHorizon.LONGER_TERM
            ranking_score = 5.0

            evidence = [
                CandidateEvidence(
                    factor="academic_standing",
                    display_name="Academic Standing",
                    current_value=f"CGPA {cgpa:.2f} · {att:.0f}% Att",
                    target_or_threshold="Maintained",
                    unit="",
                    source=RecommendationSource.ACADEMIC_DATA,
                    impact_detail="Exemplary academic discipline observed across attendance and coursework.",
                )
            ]

            return CandidateRecommendation(
                id="rec-maintain-strength",
                title="Maintain Consistent Academic Momentum",
                priority=priority,
                category=RecommendationCategory.MAINTAIN_STRENGTH,
                evidence=evidence,
                action=action,
                expected_impact=ExpectedImpact.LOW,
                source=RecommendationSource.ACADEMIC_DATA,
                time_horizon=time_horizon,
                risk_factor="Low Risk",
                technical_details={"standing": "strong", "risk_level": risk_lvl},
                ranking_score=ranking_score,
            )

        return None



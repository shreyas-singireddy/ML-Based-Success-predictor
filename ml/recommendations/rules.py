# Rule 5: Academic Trend & CGPA Trajectory Recommendation
# ---------------------------------------------------------------------------

class AcademicTrendRecommendationRule(BaseRecommendationRule):
    """
    Evaluates prior CGPA, predicted CGPA, and semester-over-semester trend.
    """
    def evaluate(
        self,
        raw_data: Dict[str, Any],
        cgpa_prediction: Optional[Any],
        risk_prediction: Optional[Any],
        explanation: Optional[Any],
        simulation_data: Optional[Dict[str, Any]],
    ) -> Optional[CandidateRecommendation]:
        prev_cgpa = raw_data.get("previous_cgpa")
        if prev_cgpa is None:
            return None

        prev_val = float(prev_cgpa)
        pred_val = getattr(cgpa_prediction, "predicted_cgpa", None) if cgpa_prediction else None

        # Extract trend from feature summary if available
        trend_val = 0.0
        if cgpa_prediction and hasattr(cgpa_prediction, "feature_summary") and cgpa_prediction.feature_summary:
            trend_val = getattr(cgpa_prediction.feature_summary, "previous_cgpa_trend", 0.0) or 0.0

        shap_val = self._extract_shap_for_feature(explanation, "previous_cgpa")

        # Downward trajectory or low baseline CGPA
        if trend_val < RecommendationPolicyConfig.TREND_SHARP_DROP_THRESHOLD or prev_val < RecommendationPolicyConfig.CGPA_CRITICAL_THRESHOLD:
            priority = RecommendationPriority.HIGH
            action = (
                f"Your academic trajectory reflects a noticeable decline (trend: {trend_val:+.2f}, prior CGPA: {prev_val:.2f}). "
                f"Schedule an academic advising session to review course load balance and study techniques."
            )
            time_horizon = TimeHorizon.THIS_WEEK
            ranking_score = 32.0 + abs(trend_val) * 10.0
            category = RecommendationCategory.STUDY_IMPROVEMENT
        elif trend_val < RecommendationPolicyConfig.TREND_MILD_DROP_THRESHOLD or prev_val < RecommendationPolicyConfig.CGPA_WARNING_THRESHOLD:
            priority = RecommendationPriority.MEDIUM
            action = (
                f"Prior CGPA ({prev_val:.2f}) is below the target benchmark ({RecommendationPolicyConfig.CGPA_TARGET}). "
                f"Set weekly study goals and allocate focused study blocks for heavy-credit core courses."
            )
            time_horizon = TimeHorizon.NEXT_30_DAYS
            ranking_score = 22.0
            category = RecommendationCategory.CGPA_IMPROVEMENT
        else:
            return None

        impact = ExpectedImpact.MEDIUM
        source = RecommendationSource.COMBINED if shap_val is not None else RecommendationSource.ACADEMIC_DATA

        evidence = [
            CandidateEvidence(
                factor="previous_cgpa",
                display_name="Prior CGPA & Trend",
                current_value=round(prev_val, 2),
                target_or_threshold=RecommendationPolicyConfig.CGPA_TARGET,
                unit="points",
                source=source,
                shap_contribution=shap_val,
                impact_detail=f"Semester trend: {trend_val:+.2f} CGPA points.",
            )
        ]

        return CandidateRecommendation(
            id="rec-trajectory-improvement",
            title="Stabilize Academic Performance Trajectory",
            priority=priority,
            category=category,
            evidence=evidence,
            action=action,
            expected_impact=impact,
            source=source,
            time_horizon=time_horizon,
            risk_factor="Academic Trend",
            technical_details={
                "previous_cgpa": prev_val,
                "predicted_cgpa": pred_val,
                "academic_trend": trend_val,
            },
            ranking_score=ranking_score,
        )



"""
Deterministic Recommendation Rules Engine for Phase 8.

Translates verified multi-phase academic evidence (Data, ML Predictions, Risk Factors,
SHAP Explanations, What-If Simulations) into ranked, personalized, actionable recommendations.

Rules:
1. AttendanceRecommendationRule
2. BacklogRecommendationRule
3. MidtermExamRecommendationRule
4. InternalAssessmentRecommendationRule
5. AcademicTrendRecommendationRule
6. StrengthMaintenanceRule
"""

from abc import ABC, abstractmethod
from typing import Dict, List, Any, Optional
import math

from ml.recommendations.recommendation_config import (
    RecommendationCategory,
    RecommendationPriority,
    RecommendationSource,
    ExpectedImpact,
    TimeHorizon,
    RecommendationPolicyConfig,
    PRIORITY_SEVERITY_ORDER,
)


class CandidateEvidence:
    """Represents a discrete piece of evidence supporting a recommendation."""
    def __init__(
        self,
        factor: str,
        display_name: str,
        current_value: Optional[Any],
        target_or_threshold: Optional[Any],
        unit: str,
        source: RecommendationSource,
        simulated_value: Optional[Any] = None,
        shap_contribution: Optional[float] = None,
        impact_detail: Optional[str] = None,
    ):
        self.factor = factor
        self.display_name = display_name
        self.current_value = current_value
        self.target_or_threshold = target_or_threshold
        self.unit = unit
        self.source = source
        self.simulated_value = simulated_value
        self.shap_contribution = shap_contribution
        self.impact_detail = impact_detail

    def to_dict(self) -> Dict[str, Any]:
        return {
            "factor": self.factor,
            "display_name": self.display_name,
            "current_value": self.current_value,
            "target_or_threshold": self.target_or_threshold,
            "unit": self.unit,
            "source": self.source.value,
            "simulated_value": self.simulated_value,
            "shap_contribution": self.shap_contribution,
            "impact_detail": self.impact_detail,
        }


class CandidateRecommendation:
    """Candidate recommendation generated by a rule before final ranking and filtering."""
    def __init__(
        self,
        id: str,
        title: str,
        priority: RecommendationPriority,
        category: RecommendationCategory,
        evidence: List[CandidateEvidence],
        action: str,
        expected_impact: ExpectedImpact,
        source: RecommendationSource,
        time_horizon: TimeHorizon,
        risk_factor: Optional[str] = None,
        technical_details: Optional[Dict[str, Any]] = None,
        ranking_score: float = 0.0,
    ):
        self.id = id
        self.title = title
        self.priority = priority
        self.category = category
        self.evidence = evidence
        self.action = action
        self.expected_impact = expected_impact
        self.source = source
        self.time_horizon = time_horizon
        self.risk_factor = risk_factor
        self.technical_details = technical_details or {}
        self.ranking_score = ranking_score

    def to_dict(self) -> Dict[str, Any]:
        return {
            "id": self.id,
            "title": self.title,
            "priority": self.priority.value,
            "category": self.category.value,
            "evidence": [e.to_dict() for e in self.evidence],
            "action": self.action,
            "expected_impact": self.expected_impact.value,
            "source": self.source.value,
            "time_horizon": self.time_horizon.value,
            "risk_factor": self.risk_factor,
            "technical_details": self.technical_details,
        }


class BaseRecommendationRule(ABC):
    """Abstract base class for evidence-driven recommendation rules."""
    @abstractmethod
    def evaluate(
        self,
        raw_data: Dict[str, Any],
        cgpa_prediction: Optional[Any],
        risk_prediction: Optional[Any],
        explanation: Optional[Any],
        simulation_data: Optional[Dict[str, Any]],
    ) -> Optional[CandidateRecommendation]:
        """Evaluates inputs and returns a CandidateRecommendation if applicable, else None."""
        pass

    @staticmethod
    def _extract_shap_for_feature(explanation: Optional[Any], feature_name: str) -> Optional[float]:
        """Extracts SHAP value for a given feature from Phase 5 explanation schema or dict."""
        if not explanation:
            return None
        factors = []
        if hasattr(explanation, "top_factors"):
            factors = getattr(explanation, "top_factors", [])
        elif isinstance(explanation, dict) and "top_factors" in explanation:
            factors = explanation["top_factors"]

        for f in factors:
            fname = f.feature_name if hasattr(f, "feature_name") else f.get("feature_name", "")
            if fname == feature_name:
                val = f.shap_value if hasattr(f, "shap_value") else f.get("shap_value", None)
                return round(float(val), 4) if val is not None else None
        return None

    @staticmethod
    def _determine_simulation_impact(simulation_delta: Optional[Dict[str, Any]]) -> ExpectedImpact:
        """Determines evidence-backed impact level from actual What-If simulation deltas."""
        if not simulation_delta:
            return ExpectedImpact.UNKNOWN

        cgpa_delta = simulation_delta.get("cgpa_delta", 0.0)
        risk_score_delta = simulation_delta.get("risk_score_delta", 0.0)  # negative means risk reduced

        if (
            cgpa_delta >= RecommendationPolicyConfig.SIMULATION_HIGH_IMPACT_CGPA_DELTA
            or risk_score_delta <= -RecommendationPolicyConfig.SIMULATION_HIGH_IMPACT_RISK_SCORE_DELTA
        ):
            return ExpectedImpact.HIGH
        elif (
            cgpa_delta >= RecommendationPolicyConfig.SIMULATION_MED_IMPACT_CGPA_DELTA
            or risk_score_delta <= -RecommendationPolicyConfig.SIMULATION_MED_IMPACT_RISK_SCORE_DELTA
        ):
            return ExpectedImpact.MEDIUM
        elif cgpa_delta > 0.0 or risk_score_delta < 0.0:
            return ExpectedImpact.LOW

        return ExpectedImpact.UNKNOWN



# Rule 3: Mid-Term Examination Recommendation
# ---------------------------------------------------------------------------

class MidtermExamRecommendationRule(BaseRecommendationRule):
    """
    Evaluates mid-term examination averages (mid_1, mid_2) against institutional targets,
    SHAP contributions, and mid-term improvement simulations.
    """
    def evaluate(
        self,
        raw_data: Dict[str, Any],
        cgpa_prediction: Optional[Any],
        risk_prediction: Optional[Any],
        explanation: Optional[Any],
        simulation_data: Optional[Dict[str, Any]],
    ) -> Optional[CandidateRecommendation]:
        m1 = raw_data.get("mid_1")
        m2 = raw_data.get("mid_2")
        if m1 is None or m2 is None:
            return None

        m1_val = float(m1)
        m2_val = float(m2)
        mid_avg = (m1_val + m2_val) / 2.0

        if mid_avg >= RecommendationPolicyConfig.MIDTERM_TARGET:
            return None

        shap_val = self._extract_shap_for_feature(explanation, "mid_1")
        shap_val_2 = self._extract_shap_for_feature(explanation, "mid_2")
        combined_shap = None
        if shap_val is not None or shap_val_2 is not None:
            combined_shap = (shap_val or 0.0) + (shap_val_2 or 0.0)

        sim_delta = simulation_data.get("mid_terms") if simulation_data else None

        if mid_avg < RecommendationPolicyConfig.MIDTERM_CRITICAL_THRESHOLD:
            priority = RecommendationPriority.CRITICAL
            action = (
                f"Your average mid-term examination performance ({mid_avg:.1f}/100) is critically below the institutional benchmark "
                f"({RecommendationPolicyConfig.MIDTERM_CRITICAL_THRESHOLD}). Conduct a comprehensive syllabus review, "
                f"attend faculty office hours, and utilize department tutorial sessions before end-semester finals."
            )
            time_horizon = TimeHorizon.THIS_WEEK
            ranking_score = 38.0 + (RecommendationPolicyConfig.MIDTERM_TARGET - mid_avg) * 0.5
        elif mid_avg < RecommendationPolicyConfig.MIDTERM_WARNING_THRESHOLD:
            priority = RecommendationPriority.HIGH
            action = (
                f"Mid-term examination average ({mid_avg:.1f}/100) indicates vulnerability in core coursework. "
                f"Review mid-term question papers, identify low-scoring topics, and complete practice problem sets."
            )
            time_horizon = TimeHorizon.THIS_WEEK
            ranking_score = 28.0 + (RecommendationPolicyConfig.MIDTERM_TARGET - mid_avg) * 0.5
        else:
            priority = RecommendationPriority.MEDIUM
            action = (
                f"Mid-term average ({mid_avg:.1f}/100) meets passing standards but falls short of the target benchmark "
                f"({RecommendationPolicyConfig.MIDTERM_TARGET}). Intensify revision on weaker modules to boost final CGPA."
            )
            time_horizon = TimeHorizon.NEXT_30_DAYS
            ranking_score = 18.0 + (RecommendationPolicyConfig.MIDTERM_TARGET - mid_avg) * 0.5

        if combined_shap is not None and combined_shap < -0.2:
            ranking_score += abs(combined_shap) * 10.0

        impact = self._determine_simulation_impact(sim_delta)
        if impact == ExpectedImpact.UNKNOWN:
            impact = ExpectedImpact.MEDIUM

        sources = [RecommendationSource.ACADEMIC_DATA, RecommendationSource.RISK_POLICY]
        if combined_shap is not None:
            sources.append(RecommendationSource.XAI)
        if sim_delta:
            sources.append(RecommendationSource.WHAT_IF_SIMULATION)
        source = RecommendationSource.COMBINED if len(sources) > 1 else sources[0]

        impact_detail = None
        sim_val = None
        if sim_delta:
            sim_val = sim_delta.get("simulated_value")
            cgpa_diff = sim_delta.get("cgpa_delta", 0.0)
            trans = sim_delta.get("risk_transition", "")
            impact_detail = f"Simulating mid-term improvement (to {sim_val}) yields +{cgpa_diff:.2f} predicted CGPA ({trans})."

        evidence = [
            CandidateEvidence(
                factor="mid_term_average",
                display_name="Mid-Term Average",
                current_value=round(mid_avg, 1),
                target_or_threshold=RecommendationPolicyConfig.MIDTERM_TARGET,
                unit="marks",
                source=source,
                simulated_value=sim_val,
                shap_contribution=round(combined_shap, 4) if combined_shap is not None else None,
                impact_detail=impact_detail,
            )
        ]

        return CandidateRecommendation(
            id="rec-midterm-preparation",
            title="Strengthen Mid-Term & Exam Preparation",
            priority=priority,
            category=RecommendationCategory.EXAM_PREPARATION,
            evidence=evidence,
            action=action,
            expected_impact=impact,
            source=source,
            time_horizon=time_horizon,
            risk_factor="Mid-Term Performance",
            technical_details={
                "mid_1": m1_val,
                "mid_2": m2_val,
                "mid_avg": mid_avg,
                "combined_shap": combined_shap,
            },
            ranking_score=ranking_score,
        )



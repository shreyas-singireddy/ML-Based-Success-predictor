# Rule 1: Attendance Recommendation
# ---------------------------------------------------------------------------

class AttendanceRecommendationRule(BaseRecommendationRule):
    """
    Evaluates attendance evidence against institutional policy thresholds,
    SHAP contributions, and What-If attendance simulation results.
    """
    def evaluate(
        self,
        raw_data: Dict[str, Any],
        cgpa_prediction: Optional[Any],
        risk_prediction: Optional[Any],
        explanation: Optional[Any],
        simulation_data: Optional[Dict[str, Any]],
    ) -> Optional[CandidateRecommendation]:
        attendance = raw_data.get("attendance_percentage")
        if attendance is None:
            return None

        att_val = float(attendance)
        shap_val = self._extract_shap_for_feature(explanation, "attendance_percentage")
        sim_delta = simulation_data.get("attendance") if simulation_data else None

        # Check if attendance is below institutional target
        if att_val >= RecommendationPolicyConfig.ATTENDANCE_SAFE_TARGET:
            return None

        # Determine priority based on policy + risk + SHAP
        if att_val < RecommendationPolicyConfig.ATTENDANCE_CRITICAL_THRESHOLD:
            priority = RecommendationPriority.CRITICAL
            action = (
                f"Your current attendance ({att_val:.1f}%) is below the critical threshold of "
                f"{RecommendationPolicyConfig.ATTENDANCE_CRITICAL_THRESHOLD}%. Prioritize immediate, "
                f"unbroken attendance in all remaining lecture and lab sessions to reach the safe target "
                f"of {RecommendationPolicyConfig.ATTENDANCE_SAFE_TARGET}%."
            )
            time_horizon = TimeHorizon.THIS_WEEK
            ranking_score = 40.0 + (RecommendationPolicyConfig.ATTENDANCE_SAFE_TARGET - att_val)
        elif att_val < RecommendationPolicyConfig.ATTENDANCE_WARNING_THRESHOLD:
            priority = RecommendationPriority.HIGH
            action = (
                f"Your attendance ({att_val:.1f}%) is below the institutional requirement of "
                f"{RecommendationPolicyConfig.ATTENDANCE_WARNING_THRESHOLD}%. Attend all upcoming "
                f"scheduled classes to avoid examination eligibility flags and reach {RecommendationPolicyConfig.ATTENDANCE_SAFE_TARGET}%."
            )
            time_horizon = TimeHorizon.THIS_WEEK
            ranking_score = 30.0 + (RecommendationPolicyConfig.ATTENDANCE_SAFE_TARGET - att_val)
        else:
            priority = RecommendationPriority.MEDIUM
            action = (
                f"Attendance ({att_val:.1f}%) is satisfactory but below the optimal safe target "
                f"({RecommendationPolicyConfig.ATTENDANCE_SAFE_TARGET}%). Maintain steady attendance to protect academic standing."
            )
            time_horizon = TimeHorizon.NEXT_30_DAYS
            ranking_score = 20.0 + (RecommendationPolicyConfig.ATTENDANCE_SAFE_TARGET - att_val)

        # Elevate priority if SHAP negative contribution is strong
        if shap_val is not None and shap_val < -0.2:
            if priority == RecommendationPriority.MEDIUM:
                priority = RecommendationPriority.HIGH
            ranking_score += abs(shap_val) * 10.0

        # Expected impact from real simulation
        impact = self._determine_simulation_impact(sim_delta)
        if impact == ExpectedImpact.UNKNOWN:
            impact = ExpectedImpact.HIGH if att_val < RecommendationPolicyConfig.ATTENDANCE_CRITICAL_THRESHOLD else ExpectedImpact.MEDIUM

        # Determine source
        sources = [RecommendationSource.ACADEMIC_DATA, RecommendationSource.RISK_POLICY]
        if shap_val is not None:
            sources.append(RecommendationSource.XAI)
        if sim_delta:
            sources.append(RecommendationSource.WHAT_IF_SIMULATION)
        source = RecommendationSource.COMBINED if len(sources) > 1 else sources[0]

        impact_detail = None
        sim_val = None
        if sim_delta:
            sim_val = sim_delta.get("simulated_value")
            cgpa_diff = sim_delta.get("cgpa_delta", 0.0)
            trans = sim_delta.get("risk_transition", "")
            impact_detail = f"Simulating attendance to {sim_val}% yields +{cgpa_diff:.2f} predicted CGPA ({trans})."

        evidence = [
            CandidateEvidence(
                factor="attendance_percentage",
                display_name="Class Attendance",
                current_value=round(att_val, 1),
                target_or_threshold=RecommendationPolicyConfig.ATTENDANCE_SAFE_TARGET,
                unit="%",
                source=source,
                simulated_value=sim_val,
                shap_contribution=shap_val,
                impact_detail=impact_detail,
            )
        ]

        return CandidateRecommendation(
            id="rec-attendance-improvement",
            title="Improve Class Attendance",
            priority=priority,
            category=RecommendationCategory.ATTENDANCE,
            evidence=evidence,
            action=action,
            expected_impact=impact,
            source=source,
            time_horizon=time_horizon,
            risk_factor="Attendance",
            technical_details={
                "threshold_checked": RecommendationPolicyConfig.ATTENDANCE_SAFE_TARGET,
                "shap_contribution": shap_val,
                "simulation_applied": bool(sim_delta),
            },
            ranking_score=ranking_score,
        )


